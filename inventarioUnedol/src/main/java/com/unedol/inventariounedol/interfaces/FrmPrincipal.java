    private void btnRegistrarMarcaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarMarcaActionPerformed
        
        int id = Integer.parseInt(txtIdMarca.getText());
        String nombre = txtNombreMarca.getText();
        
        try{
            Marca marca = new Marca(id, nombre);
            rmar.insertar(marca);
            
            System.out.println("Marca registrada correctamente!");
            //rmar.mostrarDatos();
            limpiar();
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
        
       
    }//GEN-LAST:event_btnRegistrarMarcaActionPerformed

    private void btnActualizarMarcaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarMarcaActionPerformed
        int id = Integer.valueOf(txtIdMarca.getText());
        String nombre = txtNombreMarca.getText();
        
        try{
            
            Marca marca = new Marca(id, nombre);
            rmar.actualizar(marca);
            
            System.out.println("Marca actualizada correctamente!");
            limpiar();
            
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showConfirmDialog(null, e.getMessage());
        }
       
        
    }//GEN-LAST:event_btnActualizarMarcaActionPerformed

    private void btnEliminarMarcaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarMarcaActionPerformed
        int id = Integer.valueOf(txtIdMarca.getText());
        String nombre = txtNombreMarca.getText();
        
        try{
            Marca marca = new Marca(id, nombre);
            rmar.eliminar(marca);
            
            System.out.println("Marca eliminada correctamente!");
            limpiar();
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showConfirmDialog(null, e.getMessage());
        }
        
    }//GEN-LAST:event_btnEliminarMarcaActionPerformed

